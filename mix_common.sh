#!/bin/bash
# mix_common.sh - body shared by 256mix.sh, 260mix.sh, mix_test12.sh and mix_test32.sh.
# Sourced after the #SBATCH header, which must define DAT_HPL, DAT_MXP and DAT_HPCG.
#
# Knobs, passed through the environment (e.g.  MIX_NVSHMEM=0 sbatch 256mix.sh):
#   BENCH         hpl (default) | hpl-mxp | hpcg
#   MIX_NVSHMEM   1 = NVSHMEM + IBGDA, the settings of the 240-A100 run (default)
#                 0 = NVSHMEM off; everything else unchanged, so NVSHMEM is the only variable
#   DAT           override the input file
#   HPL_HCA_LIST  HCA names in GPU-index order, e.g. "mlx5_0 mlx5_1 ... mlx5_7", applied on
#                 every node that sees the variable; use it when the automatic mapping is wrong
#   DRY_RUN=1     write run.sh and print the srun line without launching anything
# BENCH=hpl-mxp: hpl-mxp.sh takes flags, not --dat, and refuses to start without
# --gpu-affinity (see hplmxp_240A100.sh). N, NB, P, Q and PMAP are read from the dat file,
# so DAT= still selects the input; --fill-device 1 and the GPU monitor flags are added.

BENCH=${BENCH:-hpl}
MIX_NVSHMEM=${MIX_NVSHMEM:-1}
SIF=${SIF:-/packages/apps/simg/nvhpl_26.02.01.sif}   # release behind all three 240-A100 results of 2026-10-14

case "$BENCH" in
    hpl)     ENTRY=/workspace/hpl.sh;     DAT=${DAT:-$DAT_HPL} ;;
    hpl-mxp) ENTRY=/workspace/hpl-mxp.sh; DAT=${DAT:-$DAT_MXP} ;;
    hpcg)    ENTRY=/workspace/hpcg.sh;    DAT=${DAT:-$DAT_HPCG} ;;
    *) echo "BENCH must be hpl, hpl-mxp or hpcg (got '$BENCH')" >&2; exit 2 ;;
esac

DAT_FILE=$(readlink -f "$DAT") || { echo "input file not found: $DAT" >&2; exit 2; }
DAT_MOUNT="$(dirname "$DAT_FILE"):/my-dat-files"

if [ "$BENCH" = hpl-mxp ]; then
    MXP_N=$(awk '$2=="Ns"{print $1}' "$DAT_FILE");  MXP_NB=$(awk '$2=="NBs"{print $1}' "$DAT_FILE")
    MXP_P=$(awk '$2=="Ps"{print $1}' "$DAT_FILE");  MXP_Q=$(awk '$2=="Qs"{print $1}' "$DAT_FILE")
    MXP_ORDER=row; [ "$(awk '$2=="PMAP"{print $1}' "$DAT_FILE")" = 1 ] && MXP_ORDER=column
    for v in MXP_N MXP_NB MXP_P MXP_Q; do [ -n "${!v}" ] || { echo "$v not found in $DAT_FILE (need Ns/NBs/Ps/Qs lines)" >&2; exit 2; }; done
    # $GPU_AFF stays literal here; run.sh fills it per rank (this rank's GPU, once per local rank).
    ENTRY_ARGS="--n $MXP_N --nb $MXP_NB --nprow $MXP_P --npcol $MXP_Q --nporder $MXP_ORDER --gpu-affinity \$GPU_AFF --fill-device 1 --monitor-gpu 1 --monitor-gpu-temp-warning 80 --monitor-gpu-clock-warning 562"
    # The 240-A100 MxP run (16.15 PF) left NCCL_P2P_DISABLE unset: NCCL carries its panel broadcast.
    P2P_LINE="# NCCL_P2P_DISABLE left unset for hpl-mxp"
else
    ENTRY_ARGS="--dat /my-dat-files/$(basename "$DAT_FILE")"
    P2P_LINE="export NCCL_P2P_DISABLE=1"
fi

# Step geometry per heterogeneous component, read from the controller. The batch environment
# carries component 0's SLURM_NTASKS (240), SLURM_GPUS_PER_NODE (4) and SLURM_MEM_PER_NODE,
# and srun applies them to every component unless each section states its own: the first
# 256 run died with "can't honor --ntasks-per-node set to 8 ... requested tasks 240".
HET=${SLURM_HET_SIZE:-1}
HET_NODES=(); HET_TASKS=(); HET_CPT=(); TOTAL=0
if [ "$HET" -gt 1 ]; then
    for i in $(seq 0 $((HET - 1))); do
        jv="SLURM_JOB_ID_HET_GROUP_$i"; rec=$(scontrol -o show job "${!jv:-}" 2>/dev/null)
        nodes=$(grep -o 'NumNodes=[0-9]*' <<<"$rec" | head -1 | cut -d= -f2)
        n=$(grep -o 'NumTasks=[0-9]*' <<<"$rec" | head -1 | cut -d= -f2)
        tpn=$(grep -o 'NtasksPerN:B:S:C=[0-9]*' <<<"$rec" | head -1 | cut -d= -f2)
        cpt=$(grep -o 'CPUs/Task=[0-9]*' <<<"$rec" | head -1 | cut -d= -f2)
        [ -z "$n" ] && [ -n "$nodes" ] && [ -n "$tpn" ] && n=$((nodes * tpn))
        [ -n "$nodes" ] && [ -n "$n" ] || { echo "component $i (job ${!jv:-?}): cannot read NumNodes/NumTasks from scontrol" >&2; exit 2; }
        HET_NODES[$i]=$nodes; HET_TASKS[$i]=$n; HET_CPT[$i]=${cpt:-${SLURM_CPUS_PER_TASK:-12}}; TOTAL=$((TOTAL + n))
    done
else
    TOTAL=${SLURM_NTASKS:-0}
fi

echo "==============================================================================="
echo "---------------- ${BENCH} mixed run start $(date) ------------------"
echo "job ${SLURM_JOB_ID:-?}  het components=$HET  tasks=$TOTAL  nvshmem=$MIX_NVSHMEM"
echo "nodes: ${SLURM_JOB_NODELIST:-?}"
for i in $(seq 1 $((HET - 1))); do v="SLURM_JOB_NODELIST_HET_GROUP_$i"; echo "  component $i: ${!v:-?}"; done
command -v scontrol >/dev/null && [ -n "${SLURM_JOB_ID:-}" ] && scontrol write batch_script "$SLURM_JOB_ID" - | grep -v '^ *echo '
echo "input: $DAT_FILE"; cat "$DAT_FILE"
[ "$BENCH" = hpl-mxp ] && echo "hpl-mxp flags: $ENTRY_ARGS"

mkdir -p mymix
cat > mymix/run.sh <<EOF
#!/bin/bash
# Generated by mix_common.sh. Runs once per rank inside the container.
# Resolves the IB device for this rank's GPU: on a node with one HCA every rank uses it,
# as the 240-A100 script did; on a node with one HCA per GPU (8-way HGX) each rank takes
# the HCA on its GPU's NUMA node, k-th HCA for the k-th GPU there. HPL_HCA_LIST overrides.
SYSFS=\${SYSFS:-/sys}
GPU_N=\${SLURM_GPUS_ON_NODE:-\$(nvidia-smi -L 2>/dev/null | wc -l)}
GPU_IDX=\${CUDA_VISIBLE_DEVICES%%,*}; GPU_IDX=\${GPU_IDX:-\${SLURM_LOCALID:-0}}
GPU_AFF=\$GPU_IDX; for ((i = 1; i < GPU_N; i++)); do GPU_AFF+=":\$GPU_IDX"; done   # hpl-mxp --gpu-affinity

gpu_numa() { b=\$(nvidia-smi --query-gpu=pci.bus_id --format=csv,noheader -i "\$1" | tr 'A-F' 'a-f' | sed 's/^0000//'); cat "\$SYSFS/bus/pci/devices/\$b/numa_node" 2>/dev/null || echo -1; }
hca_numa() { cat "\$SYSFS/class/infiniband/\$1/device/numa_node" 2>/dev/null || echo -1; }

HCAS=()
for d in "\$SYSFS"/class/infiniband/*; do
    [ -e "\$d" ] || continue
    case "\$(cat "\$d/ports/1/state" 2>/dev/null)" in *ACTIVE*) HCAS+=("\$(basename "\$d")") ;; esac
done
[ \${#HCAS[@]} -gt 0 ] && { IFS=\$'\n' HCAS=(\$(printf '%s\n' "\${HCAS[@]}" | sort -V)); unset IFS; }

MAP=()   # MAP[i] = HCA for GPU index i on this node
if [ -n "\${HPL_HCA_LIST:-}" ]; then
    MAP=(\$HPL_HCA_LIST)
elif [ \${#HCAS[@]} -ge "\$GPU_N" ] && [ "\$GPU_N" -gt 1 ]; then
    used=()   # per-NUMA-node count of GPUs already mapped (index 99 = unknown NUMA)
    for i in \$(seq 0 \$((GPU_N - 1))); do
        n=\$(gpu_numa "\$i"); key=\$n; [ "\$key" -ge 0 ] 2>/dev/null || key=99; k=\${used[\$key]:-0}; pick=""; c=0
        for h in "\${HCAS[@]}"; do
            [ "\$(hca_numa "\$h")" = "\$n" ] || continue
            [ "\$c" -eq "\$k" ] && { pick=\$h; break; }
            c=\$((c + 1))
        done
        MAP+=("\${pick:-\${HCAS[\$((i % \${#HCAS[@]}))]}}"); used[\$key]=\$((k + 1))
    done
else
    for i in \$(seq 1 "\$GPU_N"); do MAP+=("\${HCAS[0]:-mlx5_0}"); done
fi
HCA=\${MAP[\$GPU_IDX]}
PE_MAP=\$(printf '%s:1,' "\${MAP[@]}"); PE_MAP=\${PE_MAP%,}

IPOIB=ib0
for n in "\$SYSFS"/class/net/ib*; do
    [ -e "\$n" ] && [ "\$(cat "\$n/operstate" 2>/dev/null)" = up ] && { IPOIB=\$(basename "\$n"); break; }
done

echo "On node \$(hostname): rank=\${PMIX_RANK:-\${SLURM_PROCID:-?}} local=\${SLURM_LOCALID:-?} gpu=\$GPU_IDX gpus_on_node=\$GPU_N hca=\$HCA pe_map=\$PE_MAP ipoib=\$IPOIB nvshmem=$MIX_NVSHMEM"

export OMP_NUM_THREADS=\${SLURM_CPUS_PER_TASK:-12}
export OMP_PROC_BIND=close
export OMP_PLACES=cores
export OMPI_MCA_pml=ucx
export OMPI_MCA_coll=^ucc
export OMPI_MCA_btl=^openib
export PMIX_MCA_gds=hash
export UCX_TLS=dc_x,sm,self,cuda_ipc,cuda_copy,gdr_copy
export UCX_NET_DEVICES=\${HCA}:1
export UCX_SOCKADDR_TLS_PRIORITY=rdmacm
export UCX_POSIX_USE_PROC_LINK=n
export UCX_IB_GDR_DIRECT_RDMA=y
export NCCL_DEBUG=WARN
export NCCL_NET=IB
export NCCL_IB_HCA=\$HCA
export NCCL_SOCKET_IFNAME=\$IPOIB
export NCCL_IB_GID_INDEX=0
export NCCL_IB_PCI_RELAXED_ORDERING=1
export NCCL_CROSS_NIC=0
$P2P_LINE
export MONITOR_GPU=1
export GPU_TEMP_WARNING=80
export GPU_CLOCK_WARNING=562
if [ "$MIX_NVSHMEM" = 1 ]; then
    export HPL_USE_NVSHMEM=1 HPL_NVSHMEM_SWAP=1 HPL_ALLOC_HUGEPAGES=1
    export NVSHMEM_REMOTE_TRANSPORT=ibrc NVSHMEM_HCA_PE_MAPPING=\$PE_MAP NVSHMEM_FORCE_IBGDA=1 NVSHMEM_DEBUG=WARN
    export NCCL_COLLNET_ENABLE=1
else
    export HPL_USE_NVSHMEM=0 HPL_NVSHMEM_SWAP=0 HPL_NVSHMEM_INIT=0
fi
exec $ENTRY $ENTRY_ARGS
EOF
chmod +x mymix/run.sh
SCRIPT_MOUNT="$(readlink -f mymix):/mymix"

CMD="apptainer run --nv -B $DAT_MOUNT -B $SCRIPT_MOUNT $SIF /mymix/run.sh"
if [ "$HET" -gt 1 ]; then
    # One srun, one colon-separated section per component, each with its own -N/-n/-c.
    # Component 0's values are dropped from the environment so they cannot become defaults.
    unset SLURM_NTASKS SLURM_NPROCS SLURM_NTASKS_PER_NODE SLURM_NNODES SLURM_JOB_NUM_NODES \
          SLURM_GPUS_PER_NODE SLURM_MEM_PER_NODE SLURM_MEM_PER_CPU SLURM_CPUS_PER_TASK SRUN_CPUS_PER_TASK
    SRUN="srun"
    for i in $(seq 0 $((HET - 1))); do
        [ "$i" -gt 0 ] && SRUN+=" :"
        SRUN+=" --het-group=$i --mpi=pmix --export=ALL -N ${HET_NODES[$i]} -n ${HET_TASKS[$i]} --ntasks-per-node=$((HET_TASKS[$i] / HET_NODES[$i])) -c ${HET_CPT[$i]} $CMD"
    done
else
    SRUN="srun --mpi=pmix --export=ALL${SLURM_NTASKS:+ -n $SLURM_NTASKS} $CMD"
fi
if [ "${DRY_RUN:-0}" = 1 ]; then
    echo "--- DRY_RUN: mymix/run.sh ---"; cat mymix/run.sh; echo "--- srun ---"; echo "$SRUN"; exit 0
fi
$SRUN
echo "---------------- ${BENCH} mixed run end $(date) ------------------"
echo "==============================================================================="
